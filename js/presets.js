/**
 * Hand-tuned ramp templates for stylized / hand-painted 3D materials.
 * Values are intentionally kept in plain data so a preset can be serialized,
 * previewed, cloned into a strip or extended by users.
 */

const preset = (id, name, category, description, stops, options = {}) => ({
  id,
  name,
  category,
  description,
  interpolation: options.interpolation || "smooth",
  curve: options.curve || { in: 0, out: 1 },
  steps: options.steps || 4,
  stops: stops.map(([pos, color]) => ({ pos, color })),
});

